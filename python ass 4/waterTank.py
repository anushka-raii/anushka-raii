
#Water Tank Volume A cylindrical water tank has a radius of 3.5 meters and a height of 10 meters.Write a Python program to calculate the total volume of water it can store. Use π = 3.14159. 
pi = 3.14159
radius = 3.5
height = 10

volume = pi * radius**2 * height
print("Water Tank Volume:", volume, "cubic meters")

