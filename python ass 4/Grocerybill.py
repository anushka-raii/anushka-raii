#Grocery Bill Splitter A group of 4 friends went shopping. They bought the following items: Apples: ₹120 Bread: ₹40 Milk: ₹50 Eggs: ₹90 
#Write a Python program to calculate the total bill and split it equally among the friends. Show the amount each one has to pay.

total = 120 + 40 + 50 + 90
split = total / 4

print("Total bill: ₹", total)
print("Each friend pays: ₹", split)


